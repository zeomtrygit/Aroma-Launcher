struct BackgroundOccluder {
    int x;
    int y;
    int width;
    int height;
};

static BackgroundOccluder gBackgroundOccluders[8] = {};
static int gBackgroundOccluderCount = 0;
static bool gApplyingBackgroundOcclusion = false;

static void clearBackgroundOccluders()
{
    gBackgroundOccluderCount = 0;
}

static void addBackgroundOccluder(
    int x,
    int y,
    int width,
    int height)
{
    if (width <= 0 ||
        height <= 0 ||
        gBackgroundOccluderCount >=
            static_cast<int>(
                sizeof(gBackgroundOccluders) /
                sizeof(gBackgroundOccluders[0]))) {
        return;
    }

    BackgroundOccluder& occluder =
        gBackgroundOccluders[
            gBackgroundOccluderCount++];

    occluder.x = x;
    occluder.y = y;
    occluder.width = width;
    occluder.height = height;
}

static inline void drawHorizontalSpanRaw(
    OSScreenID screen,
    int y,
    int startX,
    int endX,
    uint32_t color)
{
    if (y < 0 ||
        y >= screenHeightFor(screen)) {
        return;
    }

    startX =
        std::max(
            0,
            startX);

    endX =
        std::min(
            screenWidthFor(screen) - 1,
            endX);

    if (startX > endX) {
        return;
    }

    uint32_t* pixels =
        fastWorkPixelsFor(screen);

    if (!pixels) {
        return;
    }

    uint32_t* row =
        pixels +
        static_cast<size_t>(y) *
            static_cast<size_t>(
                fastPitchPixelsFor(screen));

    std::fill(
        row + startX,
        row + endX + 1,
        color);
}

static void drawHorizontalSpan(
    OSScreenID screen,
    int y,
    int startX,
    int endX,
    uint32_t color)
{
    if (!gApplyingBackgroundOcclusion ||
        gBackgroundOccluderCount == 0) {

        drawHorizontalSpanRaw(
            screen,
            y,
            startX,
            endX,
            color);
        return;
    }

    int cursor = startX;

    while (cursor <= endX) {
        int nearestStart = endX + 1;
        int nearestEnd = endX;

        for (int i = 0;
             i < gBackgroundOccluderCount;
             i++) {

            const BackgroundOccluder& occluder =
                gBackgroundOccluders[i];

            if (y < occluder.y ||
                y >= occluder.y + occluder.height) {
                continue;
            }

            const int blockStart =
                std::max(
                    cursor,
                    occluder.x);

            const int blockEnd =
                std::min(
                    endX,
                    occluder.x +
                        occluder.width - 1);

            if (blockStart <= blockEnd &&
                blockStart < nearestStart) {
                nearestStart = blockStart;
                nearestEnd = blockEnd;
            }
        }

        if (nearestStart > endX) {
            drawHorizontalSpanRaw(
                screen,
                y,
                cursor,
                endX,
                color);
            break;
        }

        drawHorizontalSpanRaw(
            screen,
            y,
            cursor,
            nearestStart - 1,
            color);

        cursor = nearestEnd + 1;
    }
}

static void drawBackgroundVerticalSpan(
    OSScreenID screen,
    int x,
    int startY,
    int endY,
    uint32_t color)
{
    if (x < 0 ||
        x >= screenWidthFor(screen)) {
        return;
    }

    startY =
        std::max(
            0,
            startY);

    endY =
        std::min(
            screenHeightFor(screen) - 1,
            endY);

    if (startY > endY) {
        return;
    }

    uint32_t* pixels =
        fastWorkPixelsFor(screen);

    if (!pixels) {
        return;
    }

    const int pitch =
        fastPitchPixelsFor(screen);

    int cursor = startY;

    while (cursor <= endY) {
        int nearestStart = endY + 1;
        int nearestEnd = endY;

        if (gApplyingBackgroundOcclusion) {
            for (int i = 0;
                 i < gBackgroundOccluderCount;
                 i++) {

                const BackgroundOccluder& occluder =
                    gBackgroundOccluders[i];

                if (x < occluder.x ||
                    x >= occluder.x +
                        occluder.width) {
                    continue;
                }

                const int blockStart =
                    std::max(
                        cursor,
                        occluder.y);

                const int blockEnd =
                    std::min(
                        endY,
                        occluder.y +
                            occluder.height - 1);

                if (blockStart <= blockEnd &&
                    blockStart < nearestStart) {
                    nearestStart = blockStart;
                    nearestEnd = blockEnd;
                }
            }
        }

        const int visibleEnd =
            nearestStart > endY
                ? endY
                : nearestStart - 1;

        for (int y = cursor;
             y <= visibleEnd;
             y++) {
            pixels[
                static_cast<size_t>(y) *
                    static_cast<size_t>(pitch) +
                static_cast<size_t>(x)] = color;
        }

        if (nearestStart > endY) {
            break;
        }

        cursor = nearestEnd + 1;
    }
}

static void drawFilledRect(
    OSScreenID screen,
    int x,
    int y,
    int width,
    int height,
    uint32_t color)
{
    if (width <= 0 ||
        height <= 0) {
        return;
    }

    const int startY =
        std::max(
            0,
            y);

    const int endY =
        std::min(
            screenHeightFor(screen),
            y + height);

    for (int py = startY;
         py < endY;
         py++) {
        drawHorizontalSpan(
            screen,
            py,
            x,
            x + width - 1,
            color);
    }
}

static bool roundedSpanForRow(
    int py,
    int x,
    int y,
    int width,
    int height,
    int radius,
    int& outLeft,
    int& outRight)
{
    if (width <= 0 ||
        height <= 0 ||
        py < y ||
        py >= y + height) {
        return false;
    }

    radius =
        std::max(
            0,
            std::min(
                radius,
                std::min(
                    width,
                    height) /
                    2));

    outLeft = x;
    outRight = x + width - 1;

    if (radius <= 0) {
        return true;
    }

    int cornerY = 0;

    if (py < y + radius) {
        cornerY = y + radius;
    } else if (py >= y + height - radius) {
        cornerY = y + height - radius - 1;
    } else {
        return true;
    }

    const int dy =
        py - cornerY;

    const int remaining =
        std::max(
            0,
            radius * radius -
                dy * dy);

    const int reach =
        static_cast<int>(
            std::sqrt(
                static_cast<float>(
                    remaining)));

    outLeft =
        x + radius - reach;

    outRight =
        x + width - radius - 1 + reach;

    return outLeft <= outRight;
}

static void drawRoundedRect(
    OSScreenID screen,
    int x,
    int y,
    int width,
    int height,
    int radius,
    uint32_t color)
{
    if (width <= 0 ||
        height <= 0) {
        return;
    }

    const int startY =
        std::max(0, y);

    const int endY =
        std::min(
            screenHeightFor(screen),
            y + height);

    for (int py = startY;
         py < endY;
         py++) {

        int left = 0;
        int right = -1;

        if (roundedSpanForRow(
                py,
                x,
                y,
                width,
                height,
                radius,
                left,
                right)) {

            drawHorizontalSpan(
                screen,
                py,
                left,
                right,
                color);
        }
    }
}

static void drawRoundedOutline(
    OSScreenID screen,
    int x,
    int y,
    int width,
    int height,
    int radius,
    int thickness,
    uint32_t color)
{
    if (thickness <= 0) {
        return;
    }

    const int innerX = x + thickness;
    const int innerY = y + thickness;
    const int innerWidth = width - thickness * 2;
    const int innerHeight = height - thickness * 2;

    const int startY =
        std::max(0, y);

    const int endY =
        std::min(
            screenHeightFor(screen),
            y + height);

    for (int py = startY;
         py < endY;
         py++) {

        int outerLeft = 0;
        int outerRight = -1;

        if (!roundedSpanForRow(
                py,
                x,
                y,
                width,
                height,
                radius,
                outerLeft,
                outerRight)) {
            continue;
        }

        int innerLeft = 0;
        int innerRight = -1;

        const bool hasInnerSpan =
            innerWidth > 0 &&
            innerHeight > 0 &&
            roundedSpanForRow(
                py,
                innerX,
                innerY,
                innerWidth,
                innerHeight,
                std::max(
                    0,
                    radius - thickness),
                innerLeft,
                innerRight);

        if (!hasInnerSpan) {
            drawHorizontalSpan(
                screen,
                py,
                outerLeft,
                outerRight,
                color);
            continue;
        }

        drawHorizontalSpan(
            screen,
            py,
            outerLeft,
            std::min(
                outerRight,
                innerLeft - 1),
            color);

        drawHorizontalSpan(
            screen,
            py,
            std::max(
                outerLeft,
                innerRight + 1),
            outerRight,
            color);
    }
}

static uint32_t blendRgbAlpha(
    uint32_t foreground,
    uint32_t background,
    uint8_t alpha)
{
    const uint32_t srcR =
        (foreground >> 24) &
        0xFFu;

    const uint32_t srcG =
        (foreground >> 16) &
        0xFFu;

    const uint32_t srcB =
        (foreground >> 8) &
        0xFFu;

    const uint32_t bgR =
        (background >> 24) &
        0xFFu;

    const uint32_t bgG =
        (background >> 16) &
        0xFFu;

    const uint32_t bgB =
        (background >> 8) &
        0xFFu;

    const uint32_t inverse =
        255u -
        static_cast<uint32_t>(
            alpha);

    const uint32_t outR =
        (srcR * alpha +
         bgR * inverse) /
        255u;

    const uint32_t outG =
        (srcG * alpha +
         bgG * inverse) /
        255u;

    const uint32_t outB =
        (srcB * alpha +
         bgB * inverse) /
        255u;

    return
        (outR << 24) |
        (outG << 16) |
        (outB << 8);
}

static void drawFilledEllipse(
    OSScreenID screen,
    int centerX,
    int centerY,
    int radiusX,
    int radiusY,
    uint32_t color)
{
    if (radiusX <= 0 ||
        radiusY <= 0) {
        return;
    }

    const int minY =
        std::max(
            0,
            centerY - radiusY);

    const int maxY =
        std::min(
            screenHeightFor(screen) - 1,
            centerY + radiusY);

    const int64_t rx2 =
        static_cast<int64_t>(radiusX) *
        radiusX;

    const int64_t ry2 =
        static_cast<int64_t>(radiusY) *
        radiusY;

    const int64_t rhs =
        rx2 * ry2;

    for (int y = minY;
         y <= maxY;
         y++) {

        const int64_t dy =
            y - centerY;

        const int64_t dyTerm =
            dy * dy * rx2;

        const int64_t remaining =
            std::max<int64_t>(
                0,
                rhs - dyTerm);

        const int reach =
            static_cast<int>(
                std::sqrt(
                    static_cast<double>(remaining) /
                    static_cast<double>(ry2)));

        drawHorizontalSpan(
            screen,
            y,
            centerX - reach,
            centerX + reach,
            color);
    }
}

static void drawWaterBubble(
    OSScreenID screen,
    const WaterBubble& bubble)
{
    const int screenWidth =
        screenWidthFor(screen);

    const int screenHeight =
        screenHeightFor(screen);

    const int size =
        std::max(
            6,
            static_cast<int>(
                bubble.size *
                screenHeight));

    const int centerX =
        static_cast<int>(
            bubble.x *
            screenWidth);

    const int centerY =
        static_cast<int>(
            bubble.y *
            screenHeight);

    float opacity =
        bubble.opacity;

    if (!bubble.downward) {

        const float waveY =
            waveYNormalizedAt(
                bubble.x);

        const float bubbleTop =
            bubble.y -
            bubble.size *
                0.5f;

        const float fadeDistance =
            0.075f;

        opacity *=
            clamp01(
                (bubbleTop - waveY) /
                fadeDistance);
    }

    if (opacity <= 0.01f) {
        return;
    }

    const uint8_t alpha =
        static_cast<uint8_t>(
            clamp01(opacity) *
            255.0f);

    const uint32_t color =
        blendRgbAlpha(
            TEXT_COLOR,
            WATER_COLOR,
            alpha);

    const int x =
        centerX -
        size / 2;

    const int y =
        centerY -
        size / 2;

    // Port13-style square bubbles with their original softened corners.
    // drawRoundedRect is scanline-based in the fast renderer, so restoring the
    // rounded shape costs far less than the old per-pixel implementation.
    const int cornerRadius =
        std::max(
            2,
            size / 5);

    drawRoundedRect(
        screen,
        x,
        y,
        size,
        size,
        cornerRadius,
        color);
}

static void drawClassicBubble(
    OSScreenID screen,
    const ClassicBubble& bubble)
{
    const int screenWidth =
        screenWidthFor(screen);

    const int screenHeight =
        screenHeightFor(screen);

    const int radius =
        std::max(
            3,
            static_cast<int>(
                bubble.size *
                screenHeight));

    const uint8_t alpha =
        static_cast<uint8_t>(
            clamp01(
                bubble.opacity) *
            255.0f);

    drawFilledEllipse(
        screen,
        static_cast<int>(
            bubble.x *
            screenWidth),
        static_cast<int>(
            bubble.y *
            screenHeight),
        radius,
        radius,
        blendRgbAlpha(
            TEXT_COLOR,
            CLASSIC_BG_COLOR,
            alpha));
}

static void drawStaticBackground(
    OSScreenID screen)
{
    initializeAnimatedBackground();

    gApplyingBackgroundOcclusion = true;

    if (gClassicMode) {

        fastClearWorkBuffer(
            screen,
            CLASSIC_BG_COLOR);

        for (const ClassicBubble& bubble :
             gClassicBubbles) {

            drawClassicBubble(
                screen,
                bubble);
        }

        gApplyingBackgroundOcclusion = false;
        clearBackgroundOccluders();
        return;
    }

    const int width =
        screenWidthFor(screen);

    const int height =
        screenHeightFor(screen);

    // Fill the work buffer directly. This replaces a large number of calls
    // through the OSScreen pixel API while preserving exactly the same base.
    fastClearWorkBuffer(
        screen,
        WATER_COLOR);

    const int waveThickness =
        screen == SCREEN_TV
            ? 12
            : 8;

    // Only four trig calls per screen. The old naive path evaluated sine for
    // every horizontal pixel; recursively advancing sin/cos gives the same
    // wave at a fraction of the CPU cost.
    static const float PI =
        3.14159265358979323846f;

    const float horizontalSway =
        std::sin(
            gWaveTime *
            0.72f) *
        0.050f;

    const float phaseScale =
        2.0f *
        PI *
        3.15f;

    const float phaseStep =
        phaseScale /
        static_cast<float>(
            std::max(
                1,
                width - 1));

    float sine =
        std::sin(
            horizontalSway *
            phaseScale);

    float cosine =
        std::cos(
            horizontalSway *
            phaseScale);

    const float sineStep =
        std::sin(
            phaseStep);

    const float cosineStep =
        std::cos(
            phaseStep);

    // The top chunk of sky is guaranteed to be sky for every point on the
    // sine wave. Fill that huge area with fast horizontal spans once, then
    // only draw the narrow varying band column-by-column.
    const int minimumWaveCenter =
        static_cast<int>(
            (0.365f - 0.036f) *
            height);

    const int minimumWaveTop =
        std::max(
            0,
            minimumWaveCenter -
                waveThickness /
                2);

    drawFilledRect(
        screen,
        0,
        0,
        width,
        minimumWaveTop,
        SKY_COLOR);

    for (int x = 0;
         x < width;
         x++) {

        const int waveCenter =
            static_cast<int>(
                (0.365f +
                 sine *
                     0.036f) *
                height);

        const int waveTop =
            std::max(
                0,
                waveCenter -
                    waveThickness /
                    2);

        const int waveBottom =
            std::min(
                height,
                waveTop +
                    waveThickness);

        drawBackgroundVerticalSpan(
            screen,
            x,
            minimumWaveTop,
            waveTop - 1,
            SKY_COLOR);

        drawBackgroundVerticalSpan(
            screen,
            x,
            waveTop,
            waveBottom - 1,
            WAVE_COLOR);

        const float nextSine =
            sine * cosineStep +
            cosine * sineStep;

        cosine =
            cosine * cosineStep -
            sine * sineStep;

        sine = nextSine;
    }

    for (const WaterBubble& bubble :
         gWaterBubbles) {

        drawWaterBubble(
            screen,
            bubble);
    }

    gApplyingBackgroundOcclusion = false;
    clearBackgroundOccluders();
}


// ============================================================================
// Horatio D bitmap text
//
// The actual TTF file is not bundled. These glyph bitmaps were rasterized from
// the user's supplied font into include/horatio_font.h.
// ============================================================================

static std::string horatioSafeText(
    const std::string& value)
{
    std::string result;
    result.reserve(
        value.size());

    for (unsigned char c :
         value) {

        if (c >= 32 &&
            c <= 126) {

            result.push_back(
                static_cast<char>(c));

        } else {

            result.push_back('?');
        }
    }

    return result;
}


static int horatioTextWidth(
    const std::string& rawText,
    int requestedSize)
{
    const HoratioFont& font =
        horatioFontForSize(
            requestedSize);

    const std::string text =
        horatioSafeText(
            rawText);

    int width = 0;

    for (unsigned char c :
         text) {

        const HoratioGlyph& glyph =
            font.glyphs[
                static_cast<size_t>(
                    c - 32)];

        width +=
            static_cast<int>(
                glyph.advance);
    }

    return width;
}


static std::string ellipsizeHoratio(
    const std::string& rawText,
    int requestedSize,
    int maxWidth)
{
    std::string text =
        horatioSafeText(
            rawText);

    if (maxWidth <= 0) {
        return "";
    }

    if (horatioTextWidth(
            text,
            requestedSize) <=
        maxWidth) {

        return text;
    }

    const std::string dots =
        "...";

    while (!text.empty() &&
           horatioTextWidth(
               text + dots,
               requestedSize) >
               maxWidth) {

        text.pop_back();
    }

    return
        text.empty()
            ? dots
            : text + dots;
}


static void drawHoratioTextAA(
    OSScreenID screen,
    int x,
    int y,
    const std::string& rawText,
    int requestedSize,
    uint32_t color,
    uint32_t underColor)
{
    const HoratioFont& font =
        horatioFontForSize(
            requestedSize);

    const std::string text =
        horatioSafeText(
            rawText);

    int cursorX = x;

    const int baseline =
        y +
        font.ascent;

    // The packed Horatio atlas is 1-bit, so every visible pixel is fully
    // opaque. Draw contiguous runs directly into the framebuffer instead of
    // blending/calling a pixel helper once per glyph pixel.
    (void)underColor;

    for (unsigned char c :
         text) {

        const HoratioGlyph& glyph =
            font.glyphs[
                static_cast<size_t>(
                    c - 32)];

        if (glyph.width > 0 &&
            glyph.height > 0) {

            const int glyphX =
                cursorX +
                glyph.left;

            const int glyphY =
                baseline +
                glyph.top;

            const int bytesPerRow =
                (static_cast<int>(glyph.width) + 7) /
                8;

            for (int row = 0;
                 row < static_cast<int>(glyph.height);
                 row++) {

                int runStart = -1;

                for (int column = 0;
                     column < static_cast<int>(glyph.width);
                     column++) {

                    const size_t byteIndex =
                        static_cast<size_t>(glyph.offset) +
                        static_cast<size_t>(
                            row * bytesPerRow +
                            column / 8);

                    const uint8_t mask =
                        static_cast<uint8_t>(
                            0x80u >>
                            (column & 7));

                    const bool on =
                        (font.bitmap[byteIndex] & mask) != 0;

                    if (on && runStart < 0) {
                        runStart = column;
                    }

                    const bool endOfRun =
                        runStart >= 0 &&
                        (!on ||
                         column ==
                             static_cast<int>(glyph.width) - 1);

                    if (endOfRun) {
                        const int runEnd =
                            on &&
                            column ==
                                static_cast<int>(glyph.width) - 1
                                ? column
                                : column - 1;

                        drawHorizontalSpanRaw(
                            screen,
                            glyphY + row,
                            glyphX + runStart,
                            glyphX + runEnd,
                            color);

                        runStart = -1;
                    }
                }
            }
        }

        cursorX +=
            static_cast<int>(
                glyph.advance);
    }
}

