static uint32_t acquireForegroundBuffers(void*)
{
    if (gScreenBuffersReady) {
        return 0;
    }

    MEMHeapHandle mem1Heap =
        MEMGetBaseHeapHandle(
            MEM_BASE_HEAP_MEM1);

    if (!mem1Heap) {
        return 1;
    }

    // OSScreenSetBufferEx requires framebuffer addresses aligned to 0x100.
    // Using weaker alignment can shift the visible DRC scanout even when all
    // drawing coordinates are correct.
    if (gTvFramebufferSize > 0) {
        gTvFramebuffer =
            MEMAllocFromFrmHeapEx(
                mem1Heap,
                static_cast<uint32_t>(
                    gTvFramebufferSize),
                0x100);
    }

    if (gDrcFramebufferSize > 0) {
        gDrcFramebuffer =
            MEMAllocFromFrmHeapEx(
                mem1Heap,
                static_cast<uint32_t>(
                    gDrcFramebufferSize),
                0x100);
    }

    if (!gTvFramebuffer ||
        !gDrcFramebuffer) {

        gTvFramebuffer = nullptr;
        gDrcFramebuffer = nullptr;

        MEMFreeToFrmHeap(
            mem1Heap,
            MEM_FRM_HEAP_FREE_ALL);

        gScreenBuffersReady = false;
        return 1;
    }

    OSScreenSetBufferEx(
        SCREEN_TV,
        gTvFramebuffer);

    OSScreenSetBufferEx(
        SCREEN_DRC,
        gDrcFramebuffer);

    gTvSingleFramebufferSize =
        gTvFramebufferSize / 2;

    gDrcSingleFramebufferSize =
        gDrcFramebufferSize / 2;

    gTvWorkBufferIndex =
        detectOSScreenWorkBufferIndex(
            SCREEN_TV,
            gTvFramebuffer,
            gTvFramebufferSize);

    gDrcWorkBufferIndex =
        detectOSScreenWorkBufferIndex(
            SCREEN_DRC,
            gDrcFramebuffer,
            gDrcFramebufferSize);

    refreshFastWorkBufferPointers();

    fastClearWorkBuffer(
        SCREEN_TV,
        0);

    fastClearWorkBuffer(
        SCREEN_DRC,
        0);

    DCFlushRange(
        gTvWorkPixels,
        gTvSingleFramebufferSize);

    DCFlushRange(
        gDrcWorkPixels,
        gDrcSingleFramebufferSize);

    gScreenBuffersReady = true;
    return 0;
}


static uint32_t releaseForegroundBuffers(void*)
{
    gScreenBuffersReady = false;

    gTvFramebuffer = nullptr;
    gDrcFramebuffer = nullptr;
    gTvWorkPixels = nullptr;
    gDrcWorkPixels = nullptr;
    gTvSingleFramebufferSize = 0;
    gDrcSingleFramebufferSize = 0;
    gTvWorkBufferIndex = 0;
    gDrcWorkBufferIndex = 0;

    MEMHeapHandle mem1Heap =
        MEMGetBaseHeapHandle(
            MEM_BASE_HEAP_MEM1);

    if (mem1Heap) {
        MEMFreeToFrmHeap(
            mem1Heap,
            MEM_FRM_HEAP_FREE_ALL);
    }

    return 0;
}



