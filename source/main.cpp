// ============================================================================
// Classic Homebrew Launcher meta.xml reader (used by RPX cards in v1.0)
//
// Legacy HBL packages normally keep meta.xml beside the ELF/RPX executable.
// We intentionally read only the fields Aroma Launcher can currently display:
// name, short_description and long_description. Raw RPX/ELF browser entries
// intentionally use Aroma Launcher's built-in format icons instead of icon.png.
// ============================================================================

static std::string parentDirectoryOf(
    const std::string& path)
{
    const size_t slash =
        path.find_last_of('/');

    if (slash == std::string::npos) {
        return std::string();
    }

    return path.substr(0, slash);
}


static bool readTextFile(
    const std::string& path,
    std::string& outText)
{
    outText.clear();

    FILE* file =
        std::fopen(
            path.c_str(),
            "rb");

    if (file == nullptr) {
        return false;
    }

    if (std::fseek(
            file,
            0,
            SEEK_END) != 0) {

        std::fclose(file);
        return false;
    }

    const long fileSize =
        std::ftell(file);

    if (fileSize < 0 ||
        fileSize > 1024 * 1024) {

        std::fclose(file);
        return false;
    }

    if (std::fseek(
            file,
            0,
            SEEK_SET) != 0) {

        std::fclose(file);
        return false;
    }

    outText.resize(
        static_cast<size_t>(fileSize));

    if (fileSize > 0) {

        const size_t bytesRead =
            std::fread(
                &outText[0],
                1,
                static_cast<size_t>(fileSize),
                file);

        if (bytesRead !=
            static_cast<size_t>(fileSize)) {

            std::fclose(file);
            outText.clear();
            return false;
        }
    }

    std::fclose(file);
    return true;
}


static void replaceAll(
    std::string& value,
    const std::string& from,
    const std::string& to)
{
    if (from.empty()) {
        return;
    }

    size_t position = 0;

    while ((position =
                value.find(
                    from,
                    position)) !=
           std::string::npos) {

        value.replace(
            position,
            from.size(),
            to);

        position +=
            to.size();
    }
}


static std::string decodeXmlEntities(
    std::string value)
{
    replaceAll(value, "&amp;", "&");
    replaceAll(value, "&lt;", "<");
    replaceAll(value, "&gt;", ">");
    replaceAll(value, "&quot;", "\"");
    replaceAll(value, "&apos;", "'");

    return value;
}


static std::string collapseWhitespaceCopy(
    const std::string& value)
{
    std::string result;
    result.reserve(value.size());

    bool pendingSpace = false;

    for (char c : value) {

        if (std::isspace(
                static_cast<unsigned char>(c))) {

            pendingSpace =
                !result.empty();
            continue;
        }

        if (pendingSpace) {
            result.push_back(' ');
            pendingSpace = false;
        }

        result.push_back(c);
    }

    return trimCopy(result);
}


static std::string extractXmlTag(
    const std::string& xml,
    const std::string& tagName)
{
    const std::string lowerXml =
        toLowerCopy(xml);

    const std::string openTag =
        "<" +
        toLowerCopy(tagName) +
        ">";

    const std::string closeTag =
        "</" +
        toLowerCopy(tagName) +
        ">";

    const size_t start =
        lowerXml.find(openTag);

    if (start == std::string::npos) {
        return std::string();
    }

    const size_t contentStart =
        start +
        openTag.size();

    const size_t end =
        lowerXml.find(
            closeTag,
            contentStart);

    if (end == std::string::npos) {
        return std::string();
    }

    std::string value =
        trimCopy(
            xml.substr(
                contentStart,
                end - contentStart));

    static const std::string CDATA_OPEN =
        "<![CDATA[";

    static const std::string CDATA_CLOSE =
        "]]>";

    if (value.size() >=
            CDATA_OPEN.size() +
            CDATA_CLOSE.size() &&
        value.compare(
            0,
            CDATA_OPEN.size(),
            CDATA_OPEN) == 0 &&
        value.compare(
            value.size() -
                CDATA_CLOSE.size(),
            CDATA_CLOSE.size(),
            CDATA_CLOSE) == 0) {

        value =
            value.substr(
                CDATA_OPEN.size(),
                value.size() -
                    CDATA_OPEN.size() -
                    CDATA_CLOSE.size());
    }

    return decodeXmlEntities(
        trimCopy(value));
}


static void readRPXMetadata(
    const std::string& rpxPath,
    std::string& outTitle,
    std::string& outDescription)
{
    const std::string directory =
        parentDirectoryOf(rpxPath);

    if (directory.empty()) {
        return;
    }

    std::string xml;

    if (!readTextFile(
            directory +
                "/meta.xml",
            xml)) {

        return;
    }

    const std::string name =
        collapseWhitespaceCopy(
            extractXmlTag(
                xml,
                "name"));

    const std::string shortDescription =
        collapseWhitespaceCopy(
            extractXmlTag(
                xml,
                "short_description"));

    const std::string longDescription =
        collapseWhitespaceCopy(
            extractXmlTag(
                xml,
                "long_description"));

    if (!name.empty()) {
        outTitle = name;
    }

    if (!shortDescription.empty()) {
        outDescription =
            shortDescription;
    } else if (!longDescription.empty()) {
        outDescription =
            longDescription;
    }
}


// ============================================================================
// Basic RPX validation
// ============================================================================
//
// RPX files are ELF32 PowerPC binaries. librpxloader does the real loading;
// this preflight check only rejects files that are clearly truncated,
// mislabeled, or structurally impossible before the user can launch them.
// It intentionally stays conservative so unusual-but-valid RPX files are not
// rejected just because they differ from a typical wut build.
// ============================================================================

static uint16_t readRPXBE16(
    const uint8_t* ptr)
{
    return static_cast<uint16_t>(
        (static_cast<uint16_t>(ptr[0]) << 8) |
        static_cast<uint16_t>(ptr[1]));
}

static uint32_t readRPXBE32(
    const uint8_t* ptr)
{
    return
        (static_cast<uint32_t>(ptr[0]) << 24) |
        (static_cast<uint32_t>(ptr[1]) << 16) |
        (static_cast<uint32_t>(ptr[2]) << 8) |
        static_cast<uint32_t>(ptr[3]);
}

static bool isValidRPX(
    const std::string& fullPath)
{
    FILE* file =
        std::fopen(
            fullPath.c_str(),
            "rb");

    if (file == nullptr) {
        return false;
    }

    if (std::fseek(
            file,
            0,
            SEEK_END) != 0) {

        std::fclose(file);
        return false;
    }

    const long fileSizeLong =
        std::ftell(file);

    if (fileSizeLong < 52) {
        std::fclose(file);
        return false;
    }

    if (std::fseek(
            file,
            0,
            SEEK_SET) != 0) {

        std::fclose(file);
        return false;
    }

    uint8_t header[52] = {};

    const size_t readCount =
        std::fread(
            header,
            1,
            sizeof(header),
            file);

    std::fclose(file);

    if (readCount !=
        sizeof(header)) {
        return false;
    }

    // ELF magic, ELF32, big-endian, current ELF ident version.
    if (header[0] != 0x7F ||
        header[1] != 'E' ||
        header[2] != 'L' ||
        header[3] != 'F' ||
        header[4] != 1 ||
        header[5] != 2 ||
        header[6] != 1) {
        return false;
    }

    // Wii U RPX binaries target 32-bit PowerPC (EM_PPC = 20).
    if (readRPXBE16(
            header + 18) != 20) {
        return false;
    }

    // Current ELF version.
    if (readRPXBE32(
            header + 20) != 1) {
        return false;
    }

    const uint32_t sectionOffset =
        readRPXBE32(
            header + 32);

    const uint16_t headerSize =
        readRPXBE16(
            header + 40);

    const uint16_t sectionEntrySize =
        readRPXBE16(
            header + 46);

    const uint16_t sectionCount =
        readRPXBE16(
            header + 48);

    if (headerSize < 52 ||
        sectionOffset == 0 ||
        sectionEntrySize < 40 ||
        sectionCount == 0) {
        return false;
    }

    const uint64_t fileSize =
        static_cast<uint64_t>(
            fileSizeLong);

    const uint64_t sectionTableEnd =
        static_cast<uint64_t>(
            sectionOffset) +
        static_cast<uint64_t>(
            sectionEntrySize) *
        static_cast<uint64_t>(
            sectionCount);

    if (sectionTableEnd >
        fileSize) {
        return false;
    }

    return true;
}


// ============================================================================
// WUHB validation / metadata + icon loading
// ============================================================================

static bool isValidWUHB(
    const std::string& fullPath)
{
    WUHBRPXInfo rpxInfo = {};

    WUHBUtilsStatus status =
        WUHBUtils_GetRPXInfo(
            fullPath.c_str(),
            BundleSource_FileDescriptor,
            &rpxInfo);

    if (status ==
        WUHB_UTILS_RESULT_SUCCESS) {
        return true;
    }

    if (status !=
        WUHB_UTILS_RESULT_UNSUPPORTED_COMMAND) {
        return false;
    }

    // Compatibility fallback for older WUHBUtilsModule builds.
    static const char* VALIDATION_MOUNT =
        "aromalaunchercheck";

    int32_t mountResult = -1;

    status = WUHBUtils_MountBundle(
        VALIDATION_MOUNT,
        fullPath.c_str(),
        BundleSource_FileDescriptor,
        &mountResult);

    if (status !=
            WUHB_UTILS_RESULT_SUCCESS ||
        mountResult < 0) {
        return false;
    }

    int32_t unmountResult = -1;

    WUHBUtilsStatus unmountStatus =
        WUHBUtils_UnmountBundle(
            VALIDATION_MOUNT,
            &unmountResult);

    return
        unmountStatus ==
            WUHB_UTILS_RESULT_SUCCESS &&
        unmountResult >= 0;
}


static uint16_t readLE16(
    const uint8_t* ptr)
{
    return static_cast<uint16_t>(
        static_cast<uint16_t>(ptr[0]) |
        (static_cast<uint16_t>(ptr[1]) << 8));
}


// Decode the common true-colour TGA forms used by wuhbtool.
// Supports uncompressed (type 2) and RLE (type 10), 24/32 bpp.
static bool decodeTGA(
    const uint8_t* data,
    size_t dataSize,
    IconImage& outIcon)
{
    outIcon.clear();

    if (data == nullptr ||
        dataSize < 18) {
        return false;
    }

    const uint8_t idLength =
        data[0];

    const uint8_t colorMapType =
        data[1];

    const uint8_t imageType =
        data[2];

    const uint16_t width =
        readLE16(data + 12);

    const uint16_t height =
        readLE16(data + 14);

    const uint8_t bitsPerPixel =
        data[16];

    const uint8_t descriptor =
        data[17];

    if (colorMapType != 0 ||
        (imageType != 2 &&
         imageType != 10) ||
        (bitsPerPixel != 24 &&
         bitsPerPixel != 32) ||
        width == 0 ||
        height == 0) {
        return false;
    }

    const size_t pixelCount =
        static_cast<size_t>(width) *
        static_cast<size_t>(height);

    // iconTex is normally 128x128; this is just a sanity ceiling.
    if (pixelCount >
        1024u * 1024u) {
        return false;
    }

    const size_t bytesPerPixel =
        bitsPerPixel / 8;

    size_t position =
        18u +
        static_cast<size_t>(idLength);

    if (position > dataSize) {
        return false;
    }

    outIcon.width = width;
    outIcon.height = height;
    outIcon.pixels.assign(
        pixelCount,
        0);

    const bool topOrigin =
        (descriptor & 0x20) != 0;

    const bool rightOrigin =
        (descriptor & 0x10) != 0;

    size_t written = 0;

    auto storePixel =
        [&](const uint8_t* pixelBytes) {

            const uint8_t blue =
                pixelBytes[0];

            const uint8_t green =
                pixelBytes[1];

            const uint8_t red =
                pixelBytes[2];

            const uint8_t alpha =
                bytesPerPixel == 4
                    ? pixelBytes[3]
                    : 0xFF;

            const size_t fileX =
                written %
                static_cast<size_t>(width);

            const size_t fileY =
                written /
                static_cast<size_t>(width);

            const size_t x =
                rightOrigin
                    ? static_cast<size_t>(width) -
                        1u - fileX
                    : fileX;

            const size_t y =
                topOrigin
                    ? fileY
                    : static_cast<size_t>(height) -
                        1u - fileY;

            outIcon.pixels[
                y *
                    static_cast<size_t>(width) +
                x] =
                (static_cast<uint32_t>(red) << 24) |
                (static_cast<uint32_t>(green) << 16) |
                (static_cast<uint32_t>(blue) << 8) |
                static_cast<uint32_t>(alpha);

            written++;
        };

    if (imageType == 2) {

        const size_t needed =
            pixelCount *
            bytesPerPixel;

        if (position + needed >
            dataSize) {

            outIcon.clear();
            return false;
        }

        while (written <
               pixelCount) {

            storePixel(
                data + position);

            position +=
                bytesPerPixel;
        }

    } else {

        while (written <
               pixelCount) {

            if (position >=
                dataSize) {

                outIcon.clear();
                return false;
            }

            const uint8_t packet =
                data[position++];

            const size_t count =
                static_cast<size_t>(
                    (packet & 0x7F) + 1);

            if (written + count >
                pixelCount) {

                outIcon.clear();
                return false;
            }

            if (packet & 0x80) {

                if (position +
                        bytesPerPixel >
                    dataSize) {

                    outIcon.clear();
                    return false;
                }

                const uint8_t* pixel =
                    data + position;

                position +=
                    bytesPerPixel;

                for (size_t i = 0;
                     i < count;
                     i++) {

                    storePixel(pixel);
                }

            } else {

                const size_t needed =
                    count *
                    bytesPerPixel;

                if (position + needed >
                    dataSize) {

                    outIcon.clear();
                    return false;
                }

                for (size_t i = 0;
                     i < count;
                     i++) {

                    storePixel(
                        data + position);

                    position +=
                        bytesPerPixel;
                }
            }
        }
    }

    return outIcon.valid();
}


static void readWUHBMetadataAndIcon(
    const std::string& fullPath,
    std::string& outTitle,
    std::string& outDescription,
    IconImage& outIcon)
{
    outTitle = "<no title>";
    outDescription = "<no desc>";
    outIcon.clear();

    static const char* ASSET_MOUNT =
        "aromalauncherassets";

    int32_t mountResult = -1;

    WUHBUtilsStatus status =
        WUHBUtils_MountBundle(
            ASSET_MOUNT,
            fullPath.c_str(),
            BundleSource_FileDescriptor,
            &mountResult);

    if (status !=
            WUHB_UTILS_RESULT_SUCCESS ||
        mountResult < 0) {
        return;
    }

    // ------------------------------------------------------------------------
    // meta.ini
    // ------------------------------------------------------------------------

    uint8_t* buffer = nullptr;
    uint32_t bufferSize = 0;

    const std::string metaPath =
        std::string(ASSET_MOUNT) +
        ":/meta/meta.ini";

    status = WUHBUtils_ReadWholeFile(
        metaPath.c_str(),
        &buffer,
        &bufferSize);

    if (status ==
            WUHB_UTILS_RESULT_SUCCESS &&
        buffer != nullptr &&
        bufferSize > 0) {

        const std::string iniData(
            reinterpret_cast<char*>(buffer),
            bufferSize);

        WUHBMetadata metadata;

        parseWUHBMetaIni(
            iniData,
            metadata);

        outTitle =
            chooseWUHBTitle(metadata);

        outDescription =
            chooseWUHBDescription(metadata);
    }

    if (buffer != nullptr) {
        std::free(buffer);
        buffer = nullptr;
    }

    // ------------------------------------------------------------------------
    // WUHB icon
    //
    // wuhbtool stores iconTex.tga.gz. libwuhbutils transparently tries the
    // compressed ".gz" form when we request iconTex.tga.
    // ------------------------------------------------------------------------

    bufferSize = 0;

    const std::string iconPath =
        std::string(ASSET_MOUNT) +
        ":/meta/iconTex.tga";

    status = WUHBUtils_ReadWholeFile(
        iconPath.c_str(),
        &buffer,
        &bufferSize);

    if (status ==
            WUHB_UTILS_RESULT_SUCCESS &&
        buffer != nullptr &&
        bufferSize > 0) {

        decodeTGA(
            buffer,
            bufferSize,
            outIcon);
    }

    if (buffer != nullptr) {
        std::free(buffer);
        buffer = nullptr;
    }

    int32_t unmountResult = -1;

    WUHBUtils_UnmountBundle(
        ASSET_MOUNT,
        &unmountResult);
}


// ============================================================================
// Separate WUHB + RPX + ELF scanner
// ============================================================================

static void scanDirectory(
    const std::string& directory,
    std::vector<AppEntry>& wuhbApps,
    std::vector<AppEntry>& rpxApps,
    std::vector<AppEntry>& elfApps,
    bool wuhbUtilsAvailable)
{
    DIR* dir =
        opendir(directory.c_str());

    if (!dir) {
        return;
    }

    struct dirent* entry;

    while ((entry = readdir(dir)) != nullptr) {

        if (strcmp(
                entry->d_name,
                ".") == 0 ||
            strcmp(
                entry->d_name,
                "..") == 0) {
            continue;
        }

        const std::string fullPath =
            directory +
            "/" +
            entry->d_name;

        struct stat st;

        if (stat(
                fullPath.c_str(),
                &st) != 0) {
            continue;
        }

        if (S_ISDIR(st.st_mode)) {

            if (fullPath ==
                SELF_DIRECTORY) {
                continue;
            }

            scanDirectory(
                fullPath,
                wuhbApps,
                rpxApps,
                elfApps,
                wuhbUtilsAvailable);

            continue;
        }

        if (!S_ISREG(st.st_mode)) {
            continue;
        }

        const std::string filename =
            entry->d_name;

        if (isHiddenOrTempFile(filename) ||
            shouldIgnoreLauncherFile(filename)) {
            continue;
        }

        // --------------------------------------------------------------------
        // WUHB browser
        // --------------------------------------------------------------------

        if (endsWithWUHB(filename)) {

            AppEntry app;
            app.fullPath = fullPath;
            app.filename = filename;
            app.type = AppType::WUHB;
            app.title = filename;
            app.description = "<no desc>";

            if (wuhbUtilsAvailable) {

                app.valid =
                    isValidWUHB(
                        fullPath);

                if (app.valid) {

                    readWUHBMetadataAndIcon(
                        fullPath,
                        app.title,
                        app.description,
                        app.icon);

                    if (trimCopy(app.title).empty() ||
                        app.title == "<no title>") {

                        app.title =
                            filename;
                    }

                    if (trimCopy(app.description).empty()) {
                        app.description =
                            "<no desc>";
                    }

                } else {

                    app.description =
                        "WARNING: Invalid or corrupt WUHB.";
                }
            }

            wuhbApps.push_back(
                std::move(app));

            continue;
        }

        // --------------------------------------------------------------------
        // RPX browser - metadata-aware and launchable in v1.0
        // --------------------------------------------------------------------

        if (endsWithRPX(filename)) {

            AppEntry app;
            app.fullPath = fullPath;
            app.filename = filename;
            app.type = AppType::RPX;
            app.title = filename;
            app.description =
                RPX_DESCRIPTION;
            app.valid =
                isValidRPX(
                    fullPath);

            readRPXMetadata(
                fullPath,
                app.title,
                app.description);

            if (trimCopy(app.title).empty()) {
                app.title =
                    filename;
            }

            if (trimCopy(app.description).empty()) {
                app.description =
                    "<no desc>";
            }

            if (!app.valid) {
                app.description =
                    "WARNING: Invalid or corrupt RPX.";
            }

            rpxApps.push_back(
                std::move(app));

            continue;
        }

        // --------------------------------------------------------------------
        // ELF browser - listing only. Aroma Launcher never attempts to launch
        // legacy ELF executables.
        // --------------------------------------------------------------------

        if (endsWithELF(filename)) {

            AppEntry app;
            app.fullPath = fullPath;
            app.filename = filename;
            app.type = AppType::ELF;
            app.title = filename;
            app.description =
                ELF_DESCRIPTION;

            elfApps.push_back(
                std::move(app));
        }
    }

    closedir(dir);
}


// ============================================================================
// Sort + duplicate filtering, independently per browser
// ============================================================================

static void sortAndDeduplicateList(
    std::vector<AppEntry>& apps)
{
    // Deterministically choose the first path for duplicate filenames.
    std::sort(
        apps.begin(),
        apps.end(),
        [](const AppEntry& a,
           const AppEntry& b) {

            const std::string aFile =
                toLowerCopy(a.filename);

            const std::string bFile =
                toLowerCopy(b.filename);

            if (aFile != bFile) {
                return aFile < bFile;
            }

            return
                toLowerCopy(a.fullPath) <
                toLowerCopy(b.fullPath);
        });

    apps.erase(
        std::unique(
            apps.begin(),
            apps.end(),
            [](const AppEntry& a,
               const AppEntry& b) {

                return
                    toLowerCopy(a.filename) ==
                    toLowerCopy(b.filename);
            }),
        apps.end());

    // Visible case-insensitive sort.
    std::sort(
        apps.begin(),
        apps.end(),
        [](const AppEntry& a,
           const AppEntry& b) {

            const std::string aTitle =
                toLowerCopy(a.title);

            const std::string bTitle =
                toLowerCopy(b.title);

            if (aTitle != bTitle) {
                return aTitle < bTitle;
            }

            return
                toLowerCopy(a.filename) <
                toLowerCopy(b.filename);
        });
}


// ============================================================================
// Full app rescan
// ============================================================================

static bool rescanAppLists(
    std::vector<AppEntry>& wuhbApps,
    std::vector<AppEntry>& rpxApps,
    std::vector<AppEntry>& elfApps)
{
    wuhbApps.clear();
    rpxApps.clear();
    elfApps.clear();

    const WUHBUtilsStatus wuhbUtilsStatus =
        WUHBUtils_InitLibrary();

    const bool wuhbUtilsAvailable =
        wuhbUtilsStatus ==
            WUHB_UTILS_RESULT_SUCCESS;

    scanDirectory(
        APPS_DIRECTORY,
        wuhbApps,
        rpxApps,
        elfApps,
        wuhbUtilsAvailable);

    if (wuhbUtilsAvailable) {
        WUHBUtils_DeInitLibrary();
    }

    sortAndDeduplicateList(
        wuhbApps);

    sortAndDeduplicateList(
        rpxApps);

    sortAndDeduplicateList(
        elfApps);

    return wuhbUtilsAvailable;
}


// ============================================================================
// Four-item paging helpers
// ============================================================================

static int pageCountFor(
    size_t itemCount)
{
    if (itemCount == 0) {
        return 0;
    }

    return static_cast<int>(
        (itemCount +
         ITEMS_PER_PAGE - 1) /
        ITEMS_PER_PAGE);
}


static int itemsOnPage(
    size_t itemCount,
    int page)
{
    const int pages =
        pageCountFor(itemCount);

    if (pages == 0 ||
        page < 0 ||
        page >= pages) {
        return 0;
    }

    const size_t first =
        static_cast<size_t>(page) *
        ITEMS_PER_PAGE;

    const size_t remaining =
        itemCount - first;

    return static_cast<int>(
        std::min(
            remaining,
            static_cast<size_t>(
                ITEMS_PER_PAGE)));
}


static int selectedIndexFor(
    size_t itemCount,
    const BrowserState& state)
{
    const int onPage =
        itemsOnPage(
            itemCount,
            state.page);

    if (onPage <= 0 ||
        state.slot < 0 ||
        state.slot >= onPage) {
        return -1;
    }

    return
        state.page *
            ITEMS_PER_PAGE +
        state.slot;
}


static void normalizeBrowserState(
    BrowserState& state,
    size_t itemCount)
{
    const int pages =
        pageCountFor(itemCount);

    if (pages == 0) {
        state.page = 0;
        state.slot = 0;
        return;
    }

    if (state.page < 0 ||
        state.page >= pages) {
        state.page = 0;
    }

    const int onPage =
        itemsOnPage(
            itemCount,
            state.page);

    if (state.slot < 0 ||
        state.slot >= onPage) {
        state.slot = 0;
    }
}


static void changePage(
    BrowserState& state,
    size_t itemCount,
    int direction)
{
    const int pages =
        pageCountFor(itemCount);

    if (pages <= 0) {
        state.page = 0;
        state.slot = 0;
        return;
    }

    state.page += direction;

    if (state.page < 0) {
        state.page =
            pages - 1;
    } else if (state.page >=
               pages) {
        state.page = 0;
    }

    state.slot = 0;
}


static void moveWithinPage(
    BrowserState& state,
    size_t itemCount,
    int direction)
{
    const int onPage =
        itemsOnPage(
            itemCount,
            state.page);

    if (onPage <= 0) {
        state.slot = 0;
        return;
    }

    state.slot += direction;

    if (state.slot < 0) {
        state.slot =
            onPage - 1;
    } else if (state.slot >=
               onPage) {
        state.slot = 0;
    }
}

// ============================================================================
// Convert full SD filesystem path to the SD-root-relative path expected by
// librpxloader for WUHB / RPX launches.
// ============================================================================

static std::string makeLaunchPath(
    const std::string& fullPath)
{
    std::string path =
        fullPath;

    const size_t prefixLength =
        strlen(SD_FS_PREFIX);

    if (path.compare(
            0,
            prefixLength,
            SD_FS_PREFIX) == 0) {

        path.erase(
            0,
            prefixLength);
    }

    if (path.compare(
            0,
            4,
            "sd:/") == 0) {

        path.erase(
            0,
            4);
    }

    return path;
}


