static std::string toLowerCopy(const std::string& value)
{
    std::string result = value;

    std::transform(
        result.begin(),
        result.end(),
        result.begin(),
        [](unsigned char c) {
            return static_cast<char>(
                std::tolower(c));
        });

    return result;
}


static std::string trimCopy(const std::string& value)
{
    size_t start = 0;

    while (start < value.size() &&
           std::isspace(
               static_cast<unsigned char>(
                   value[start]))) {
        start++;
    }

    size_t end = value.size();

    while (end > start &&
           std::isspace(
               static_cast<unsigned char>(
                   value[end - 1]))) {
        end--;
    }

    return value.substr(
        start,
        end - start);
}


static bool endsWithExtension(
    const std::string& name,
    const std::string& extension)
{
    if (name.length() < extension.length()) {
        return false;
    }

    std::string end =
        name.substr(
            name.length() -
            extension.length());

    return toLowerCopy(end) ==
           toLowerCopy(extension);
}


static bool endsWithWUHB(const std::string& name)
{
    return endsWithExtension(
        name,
        ".wuhb");
}


static bool endsWithRPX(const std::string& name)
{
    return endsWithExtension(
        name,
        ".rpx");
}


static bool endsWithELF(const std::string& name)
{
    return endsWithExtension(
        name,
        ".elf");
}



static bool isHiddenOrTempFile(
    const std::string& filename)
{
    if (filename.empty() ||
        filename[0] == '.' ||
        filename[0] == '_') {
        return true;
    }

    const std::string lower =
        toLowerCopy(filename);

    return lower == "temp.wuhb" ||
           lower == "temp2.wuhb" ||
           lower == "temp.rpx" ||
           lower == "temp2.rpx" ||
           lower == "temp.elf" ||
           lower == "temp2.elf";
}


// Ignore Aroma Launcher itself and its old development/test builds.
static bool shouldIgnoreLauncherFile(
    const std::string& filename)
{
    const std::string lower =
        toLowerCopy(filename);

    // Existing WUHB development-build convention.
    if (lower.rfind(
            "hbl_wuhb_port",
            0) == 0) {
        return true;
    }

    if (lower ==
        "hbl_wuhb_exittest.wuhb") {
        return true;
    }

    // The project's normal build outputs should never appear as apps if
    // somebody happens to copy them into /wiiu/apps while testing.
    if (lower == "homebrew_launcher.wuhb" ||
        lower == "homebrew_launcher.rpx" ||
        lower == "homebrew_launcher.elf" ||
        lower == "hbl_wuhb.wuhb") {
        return true;
    }

    // Future/final Aroma Launcher filename variants.
    if (lower == "aroma launcher.wuhb" ||
        lower == "aroma_launcher.wuhb" ||
        lower == "aromalauncher.wuhb" ||
        lower == "aroma launcher.rpx" ||
        lower == "aroma_launcher.rpx" ||
        lower == "aromalauncher.rpx" ||
        lower == "aroma launcher.elf" ||
        lower == "aroma_launcher.elf" ||
        lower == "aromalauncher.elf") {
        return true;
    }

    if (lower.rfind("aroma launcher", 0) == 0 ||
        lower.rfind("aroma_launcher", 0) == 0 ||
        lower.rfind("aromalauncher", 0) == 0 ||
        lower.rfind("aroma-launcher", 0) == 0 ||
        lower.rfind("homebrew_launcher", 0) == 0) {
        return true;
    }

    return false;
}


// ============================================================================
// Tiny meta.ini parser
//
// Official wuhbtool currently writes [menu] longname, shortname and author.
// It does NOT define a standard description key. We still recognize several
// description spellings for custom/future bundles; otherwise v1.0 shows
// exactly "<no desc>" as requested.
// ============================================================================

static void parseWUHBMetaIni(
    const std::string& iniData,
    WUHBMetadata& metadata)
{
    std::string currentSection;
    size_t position = 0;

    while (position <= iniData.size()) {
        size_t lineEnd =
            iniData.find('\n', position);

        std::string line;

        if (lineEnd == std::string::npos) {
            line = iniData.substr(position);
            position = iniData.size() + 1;
        } else {
            line = iniData.substr(
                position,
                lineEnd - position);
            position = lineEnd + 1;
        }

        if (!line.empty() &&
            line.back() == '\r') {
            line.pop_back();
        }

        // Strip a UTF-8 BOM if one exists on the first line.
        if (line.size() >= 3 &&
            static_cast<unsigned char>(line[0]) == 0xEF &&
            static_cast<unsigned char>(line[1]) == 0xBB &&
            static_cast<unsigned char>(line[2]) == 0xBF) {
            line.erase(0, 3);
        }

        line = trimCopy(line);

        if (line.empty() ||
            line[0] == ';' ||
            line[0] == '#') {
            continue;
        }

        if (line.size() >= 2 &&
            line.front() == '[' &&
            line.back() == ']') {

            currentSection =
                toLowerCopy(
                    trimCopy(
                        line.substr(
                            1,
                            line.size() - 2)));
            continue;
        }

        if (currentSection != "menu") {
            continue;
        }

        const size_t equals =
            line.find('=');

        if (equals == std::string::npos) {
            continue;
        }

        const std::string key =
            toLowerCopy(
                trimCopy(
                    line.substr(0, equals)));

        const std::string value =
            trimCopy(
                line.substr(equals + 1));

        if (key == "longname") {
            metadata.longName = value;
        } else if (key == "shortname") {
            metadata.shortName = value;
        } else if (key == "description") {
            metadata.description = value;
        } else if (key == "long_description" ||
                   key == "longdescription") {
            metadata.longDescription = value;
        } else if (key == "short_description" ||
                   key == "shortdescription") {
            metadata.shortDescription = value;
        } else if (key == "desc") {
            metadata.desc = value;
        }
    }
}


