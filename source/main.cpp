static uint32_t blendRGBA(
    uint32_t rgba,
    uint32_t background)
{
    const uint32_t alpha =
        rgba & 0xFFu;

    if (alpha >= 255u) {
        return
            rgba &
            0xFFFFFF00u;
    }

    if (alpha == 0u) {
        return
            background &
            0xFFFFFF00u;
    }

    const uint32_t srcR =
        (rgba >> 24) &
        0xFFu;

    const uint32_t srcG =
        (rgba >> 16) &
        0xFFu;

    const uint32_t srcB =
        (rgba >> 8) &
        0xFFu;

    const uint32_t bgR =
        (background >> 24) &
        0xFFu;

    const uint32_t bgG =
        (background >> 16) &
        0xFFu;

    const uint32_t bgB =
        (background >> 8) &
        0xFFu;

    const uint32_t inverse =
        255u -
        alpha;

    const uint32_t outR =
        (srcR * alpha +
         bgR * inverse) /
        255u;

    const uint32_t outG =
        (srcG * alpha +
         bgG * inverse) /
        255u;

    const uint32_t outB =
        (srcB * alpha +
         bgB * inverse) /
        255u;

    return
        (outR << 24) |
        (outG << 16) |
        (outB << 8);
}


static void drawScaledIcon(
    OSScreenID screen,
    const IconImage& icon,
    int x,
    int y,
    int targetSize,
    uint32_t underColor)
{
    if (!icon.valid() ||
        targetSize <= 0) {
        return;
    }

    uint32_t* pixels =
        fastWorkPixelsFor(screen);

    if (!pixels) {
        return;
    }

    const int screenWidth =
        screenWidthFor(screen);

    const int screenHeight =
        screenHeightFor(screen);

    const int pitch =
        fastPitchPixelsFor(screen);

    for (int dy = 0;
         dy < targetSize;
         dy++) {

        const int py = y + dy;

        if (py < 0 ||
            py >= screenHeight) {
            continue;
        }

        const size_t sourceY =
            static_cast<size_t>(dy) *
            icon.height /
            static_cast<size_t>(targetSize);

        uint32_t* row =
            pixels +
            static_cast<size_t>(py) *
                static_cast<size_t>(pitch);

        for (int dx = 0;
             dx < targetSize;
             dx++) {

            const int px = x + dx;

            if (px < 0 ||
                px >= screenWidth) {
                continue;
            }

            const size_t sourceX =
                static_cast<size_t>(dx) *
                icon.width /
                static_cast<size_t>(targetSize);

            const uint32_t rgba =
                icon.pixels[
                    sourceY *
                        icon.width +
                    sourceX];

            if ((rgba & 0xFFu) == 0u) {
                continue;
            }

            row[px] =
                blendRGBA(
                    rgba,
                    underColor);
        }
    }
}

