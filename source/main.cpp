static void showStatusNow(
    BrowserMode mode,
    const std::vector<AppEntry>& apps,
    const BrowserState& state,
    const std::string& message)
{
    if (!canDraw()) {
        return;
    }

    drawBrowser(
        mode,
        apps,
        state,
        message);

    presentScreens();
}


// ============================================================================
// Background music
//
// Audio is intentionally isolated from ProcUI callbacks. Foreground transitions
// only call these helpers from the main loop.
// ============================================================================

static Mix_Music* gBackgroundMusic =
    nullptr;

static bool gAudioInitialized =
    false;

static bool gMusicPaused =
    false;

static bool initBackgroundMusic()
{
    if (SDL_Init(
            SDL_INIT_AUDIO) != 0) {

        return false;
    }

    if (Mix_OpenAudio(
            44100,
            MIX_DEFAULT_FORMAT,
            2,
            2048) != 0) {

        SDL_QuitSubSystem(
            SDL_INIT_AUDIO);

        return false;
    }

    SDL_RWops* musicData =
        SDL_RWFromConstMem(
            bg_music_bin,
            BG_MUSIC_BYTES);

    if (musicData ==
        nullptr) {

        Mix_CloseAudio();

        SDL_QuitSubSystem(
            SDL_INIT_AUDIO);

        return false;
    }

    gBackgroundMusic =
        Mix_LoadMUS_RW(
            musicData,
            1);

    if (gBackgroundMusic ==
        nullptr) {

        Mix_CloseAudio();

        SDL_QuitSubSystem(
            SDL_INIT_AUDIO);

        return false;
    }

    Mix_VolumeMusic(
        MIX_MAX_VOLUME *
            3 /
            5);

    if (Mix_PlayMusic(
            gBackgroundMusic,
            -1) != 0) {

        Mix_FreeMusic(
            gBackgroundMusic);

        gBackgroundMusic =
            nullptr;

        Mix_CloseAudio();

        SDL_QuitSubSystem(
            SDL_INIT_AUDIO);

        return false;
    }

    gAudioInitialized =
        true;

    gMusicPaused =
        false;

    return true;
}

static void playSelectionSound()
{
    // Selection click removed in v1.0. Keep this no-op helper so the
    // existing input/navigation code does not need to change.
}

static void pauseBackgroundMusic()
{
    if (!gAudioInitialized ||
        gBackgroundMusic ==
            nullptr ||
        gMusicPaused) {

        return;
    }

    Mix_PauseMusic();

    gMusicPaused =
        true;
}

static void resumeBackgroundMusic()
{
    if (!gAudioInitialized ||
        gBackgroundMusic ==
            nullptr ||
        !gMusicPaused) {

        return;
    }

    Mix_ResumeMusic();

    gMusicPaused =
        false;
}

static void shutdownBackgroundMusic()
{
    if (!gAudioInitialized) {
        return;
    }

    Mix_HaltMusic();

    if (gBackgroundMusic !=
        nullptr) {

        Mix_FreeMusic(
            gBackgroundMusic);

        gBackgroundMusic =
            nullptr;
    }

    Mix_CloseAudio();

    SDL_QuitSubSystem(
        SDL_INIT_AUDIO);

    gAudioInitialized =
        false;

    gMusicPaused =
        false;
}


