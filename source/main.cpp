enum class AppType {
    WUHB,
    RPX,
    ELF
};

struct IconImage {
    uint16_t width;
    uint16_t height;
    std::vector<uint32_t> pixels; // 0xRRGGBBAA

    IconImage()
        : width(0),
          height(0),
          pixels()
    {
    }

    bool valid() const
    {
        return width > 0 &&
               height > 0 &&
               pixels.size() ==
                   static_cast<size_t>(width) *
                   static_cast<size_t>(height);
    }

    void clear()
    {
        width = 0;
        height = 0;
        pixels.clear();
    }
};

struct AppEntry {
    std::string fullPath;
    std::string filename;
    std::string title;
    std::string description;
    AppType type;
    IconImage icon;
    bool valid = true;
};


