static void* gTvFramebuffer = nullptr;
static void* gDrcFramebuffer = nullptr;

static size_t gTvFramebufferSize = 0;
static size_t gDrcFramebufferSize = 0;

// Fast software renderer state. OSScreen allocates two framebuffers per screen;
// we track which half is currently the work buffer so drawing can write spans
// directly instead of calling OSScreenPutPixelEx for every single pixel.
static size_t gTvSingleFramebufferSize = 0;
static size_t gDrcSingleFramebufferSize = 0;
static int gTvWorkBufferIndex = 0;
static int gDrcWorkBufferIndex = 0;
static uint32_t* gTvWorkPixels = nullptr;
static uint32_t* gDrcWorkPixels = nullptr;
static int gTvPitchPixels = 1280;
static int gDrcPitchPixels = 896;

static bool gScreenBuffersReady = false;

static int fastScreenHeightFor(OSScreenID screen)
{
    return screen == SCREEN_TV ? 720 : 480;
}

static int detectOSScreenWorkBufferIndex(
    OSScreenID screen,
    void* framebuffer,
    size_t totalSize)
{
    if (!framebuffer || totalSize < 8) {
        return 0;
    }

    const size_t singleSize = totalSize / 2;
    uint32_t* first =
        reinterpret_cast<uint32_t*>(framebuffer);
    uint32_t* second =
        reinterpret_cast<uint32_t*>(
            static_cast<uint8_t*>(framebuffer) + singleSize);

    // Both halves start clean, so a marker written through OSScreen tells us
    // exactly which half coreinit currently considers the work buffer.
    memset(framebuffer, 0, totalSize);

    static const uint32_t marker = 0x5AC3E100;
    OSScreenPutPixelEx(screen, 0, 0, marker);

    const int index =
        first[0] == marker
            ? 0
            : (second[0] == marker ? 1 : 0);

    OSScreenClearBufferEx(screen, 0);
    return index;
}

static void refreshFastWorkBufferPointers()
{
    if (gTvFramebuffer && gTvSingleFramebufferSize > 0) {
        gTvWorkPixels =
            reinterpret_cast<uint32_t*>(
                static_cast<uint8_t*>(gTvFramebuffer) +
                gTvSingleFramebufferSize *
                    static_cast<size_t>(gTvWorkBufferIndex));

        gTvPitchPixels =
            static_cast<int>(
                gTvSingleFramebufferSize /
                static_cast<size_t>(fastScreenHeightFor(SCREEN_TV)) /
                sizeof(uint32_t));
    } else {
        gTvWorkPixels = nullptr;
    }

    if (gDrcFramebuffer && gDrcSingleFramebufferSize > 0) {
        gDrcWorkPixels =
            reinterpret_cast<uint32_t*>(
                static_cast<uint8_t*>(gDrcFramebuffer) +
                gDrcSingleFramebufferSize *
                    static_cast<size_t>(gDrcWorkBufferIndex));

        gDrcPitchPixels =
            static_cast<int>(
                gDrcSingleFramebufferSize /
                static_cast<size_t>(fastScreenHeightFor(SCREEN_DRC)) /
                sizeof(uint32_t));
    } else {
        gDrcWorkPixels = nullptr;
    }
}

static inline uint32_t* fastWorkPixelsFor(OSScreenID screen)
{
    return screen == SCREEN_TV
        ? gTvWorkPixels
        : gDrcWorkPixels;
}

static inline int fastPitchPixelsFor(OSScreenID screen)
{
    return screen == SCREEN_TV
        ? gTvPitchPixels
        : gDrcPitchPixels;
}

static inline void fastPutPixel(
    OSScreenID screen,
    uint32_t x,
    uint32_t y,
    uint32_t color)
{
    const int width =
        screen == SCREEN_TV ? 1280 : 854;
    const int height =
        screen == SCREEN_TV ? 720 : 480;

    if (x >= static_cast<uint32_t>(width) ||
        y >= static_cast<uint32_t>(height)) {
        return;
    }

    uint32_t* pixels = fastWorkPixelsFor(screen);
    if (!pixels) {
        return;
    }

    pixels[
        static_cast<size_t>(y) *
            static_cast<size_t>(fastPitchPixelsFor(screen)) +
        static_cast<size_t>(x)] = color;
}

static inline void fastClearWorkBuffer(
    OSScreenID screen,
    uint32_t color)
{
    uint32_t* pixels = fastWorkPixelsFor(screen);
    const size_t singleSize =
        screen == SCREEN_TV
            ? gTvSingleFramebufferSize
            : gDrcSingleFramebufferSize;

    if (!pixels || singleSize == 0) {
        return;
    }

    std::fill_n(
        pixels,
        singleSize / sizeof(uint32_t),
        color);
}

