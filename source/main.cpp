struct ConfirmationButtonGeometry {
    int okX;
    int declineX;
    int y;
    int width;
    int height;
};

static ConfirmationButtonGeometry confirmationButtonsForScreen(
    OSScreenID screen,
    bool isTv)
{
    const int screenWidth =
        screenWidthFor(
            screen);

    ConfirmationButtonGeometry geometry = {};

    geometry.width =
        isTv
            ? 245
            : 170;

    geometry.height =
        isTv
            ? 68
            : 48;

    geometry.y =
        isTv
            ? 410
            : 272;

    const int gap =
        isTv
            ? 34
            : 22;

    geometry.okX =
        screenWidth / 2 -
        gap / 2 -
        geometry.width;

    geometry.declineX =
        screenWidth / 2 +
        gap / 2;

    return geometry;
}

static bool pointInsideRect(
    int px,
    int py,
    int x,
    int y,
    int width,
    int height)
{
    return
        px >= x &&
        py >= y &&
        px < x + width &&
        py < y + height;
}

static int confirmationButtonAt(
    int touchX,
    int touchY)
{
    const ConfirmationButtonGeometry geometry =
        confirmationButtonsForScreen(
            SCREEN_DRC,
            false);

    if (pointInsideRect(
            touchX,
            touchY,
            geometry.okX,
            geometry.y,
            geometry.width,
            geometry.height)) {

        return 1;
    }

    if (pointInsideRect(
            touchX,
            touchY,
            geometry.declineX,
            geometry.y,
            geometry.width,
            geometry.height)) {

        return 2;
    }

    return 0;
}

