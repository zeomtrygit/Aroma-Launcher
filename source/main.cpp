static bool pointInsideCircle(
    int px,
    int py,
    int centerX,
    int centerY,
    int radius)
{
    const int dx =
        px - centerX;

    const int dy =
        py - centerY;

    return
        dx * dx +
        dy * dy <=
        radius * radius;
}

static int drcCardSlotAt(
    int touchX,
    int touchY,
    size_t itemCount,
    const BrowserState& state)
{
    const BrowserGeometry geometry =
        browserGeometryFor(
            SCREEN_DRC,
            false);

    const int count =
        itemsOnPage(
            itemCount,
            state.page);

    for (int slot = 0;
         slot < count;
         slot++) {

        const int y =
            geometry.firstY +
            slot *
                (geometry.cardHeight +
                 geometry.gap);

        if (pointInsideRect(
                touchX,
                touchY,
                geometry.cardX,
                y,
                geometry.cardWidth,
                geometry.cardHeight)) {

            return slot;
        }
    }

    return -1;
}

static int drcPageDirectionAt(
    int touchX,
    int touchY,
    size_t itemCount)
{
    if (pageCountFor(
            itemCount) <= 1) {

        return 0;
    }

    const BrowserGeometry geometry =
        browserGeometryFor(
            SCREEN_DRC,
            false);

    const int hitRadius =
        geometry.arrowRadius +
        8;

    if (pointInsideCircle(
            touchX,
            touchY,
            geometry.arrowLeftX,
            geometry.arrowY,
            hitRadius)) {

        return -1;
    }

    if (pointInsideCircle(
            touchX,
            touchY,
            geometry.arrowRightX,
            geometry.arrowY,
            hitRadius)) {

        return 1;
    }

    return 0;
}

static bool moveSelectionAnimated(
    BrowserMode mode,
    BrowserState& state,
    size_t itemCount,
    int direction,
    OSTime now)
{
    const int oldSlot =
        state.slot;

    const float visualStart =
        currentSelectionVisualSlot(
            mode,
            state.page,
            oldSlot,
            now);

    moveWithinPage(
        state,
        itemCount,
        direction);

    if (state.slot ==
        oldSlot) {

        return false;
    }

    beginSelectionAnimation(
        mode,
        state.page,
        visualStart,
        state.slot,
        now);

    playSelectionSound();
    return true;
}

static bool setSelectionAnimated(
    BrowserMode mode,
    BrowserState& state,
    size_t itemCount,
    int slot,
    OSTime now)
{
    const int count =
        itemsOnPage(
            itemCount,
            state.page);

    if (slot < 0 ||
        slot >= count ||
        slot == state.slot) {

        return false;
    }

    const float visualStart =
        currentSelectionVisualSlot(
            mode,
            state.page,
            state.slot,
            now);

    state.slot =
        slot;

    beginSelectionAnimation(
        mode,
        state.page,
        visualStart,
        state.slot,
        now);

    playSelectionSound();
    return true;
}

static bool changePageAnimated(
    BrowserMode mode,
    BrowserState& state,
    size_t itemCount,
    int direction,
    OSTime now)
{
    const int oldPage =
        state.page;

    changePage(
        state,
        itemCount,
        direction);

    if (state.page ==
        oldPage) {

        return false;
    }

    beginPageAnimation(
        mode,
        oldPage,
        state.page,
        direction,
        now);

    playSelectionSound();
    return true;
}

static uint32_t secretInputFromPressed(
    uint32_t pressed)
{
    const uint32_t relevant =
        pressed &
        (VPAD_BUTTON_UP |
         VPAD_BUTTON_DOWN |
         VPAD_BUTTON_LEFT |
         VPAD_BUTTON_RIGHT |
         VPAD_BUTTON_Y);

    if (relevant ==
            VPAD_BUTTON_UP ||
        relevant ==
            VPAD_BUTTON_DOWN ||
        relevant ==
            VPAD_BUTTON_LEFT ||
        relevant ==
            VPAD_BUTTON_RIGHT ||
        relevant ==
            VPAD_BUTTON_Y) {

        return relevant;
    }

    return 0;
}

static bool updateSecretCombo(
    uint32_t pressed,
    int& progress,
    OSTime& lastInputTime,
    OSTime now)
{
    static const uint32_t sequence[] = {
        VPAD_BUTTON_UP,
        VPAD_BUTTON_UP,
        VPAD_BUTTON_UP,
        VPAD_BUTTON_DOWN,
        VPAD_BUTTON_DOWN,
        VPAD_BUTTON_DOWN,
        VPAD_BUTTON_LEFT,
        VPAD_BUTTON_RIGHT,
        VPAD_BUTTON_LEFT,
        VPAD_BUTTON_RIGHT,
        VPAD_BUTTON_Y
    };

    static const int sequenceLength =
        static_cast<int>(
            sizeof(sequence) /
            sizeof(sequence[0]));

    const uint32_t input =
        secretInputFromPressed(
            pressed);

    if (input == 0) {
        return false;
    }

    if (progress > 0 &&
        now - lastInputTime >
            static_cast<OSTime>(
                OSMillisecondsToTicks(
                    3000))) {

        progress = 0;
    }

    lastInputTime =
        now;

    if (input ==
        sequence[progress]) {

        progress++;

        if (progress >=
            sequenceLength) {

            progress = 0;
            return true;
        }

        return false;
    }

    progress =
        input ==
            VPAD_BUTTON_UP
            ? 1
            : 0;

    return false;
}


// ============================================================================
// MAIN
// ============================================================================

int main()
{
    // ------------------------------------------------------------------------
    // ProcUI
    // ------------------------------------------------------------------------

    WHBProcInit();


    // ------------------------------------------------------------------------
    // Scan into completely separate WUHB, RPX and ELF lists
    // ------------------------------------------------------------------------

    std::vector<AppEntry> wuhbApps;
    std::vector<AppEntry> rpxApps;
    std::vector<AppEntry> elfApps;

    bool wuhbUtilsAvailable =
        rescanAppLists(
            wuhbApps,
            rpxApps,
            elfApps);


    // ------------------------------------------------------------------------
    // OSScreen setup
    // ------------------------------------------------------------------------

    OSScreenInit();

    OSScreenEnableEx(
        SCREEN_TV,
        true);

    OSScreenEnableEx(
        SCREEN_DRC,
        true);

    gTvFramebufferSize =
        OSScreenGetBufferSizeEx(
            SCREEN_TV);

    gDrcFramebufferSize =
        OSScreenGetBufferSizeEx(
            SCREEN_DRC);


    // ------------------------------------------------------------------------
    // Register foreground lifecycle callbacks.
    // This is the known-good v0.55+ lifecycle. Do not shortcut it.
    // ------------------------------------------------------------------------

    ProcUIRegisterCallback(
        PROCUI_CALLBACK_ACQUIRE,
        acquireForegroundBuffers,
        nullptr,
        100);

    ProcUIRegisterCallback(
        PROCUI_CALLBACK_RELEASE,
        releaseForegroundBuffers,
        nullptr,
        100);

    if (acquireForegroundBuffers(
            nullptr) != 0) {

        OSScreenShutdown();
        WHBProcShutdown();
        return 1;
    }


    // ------------------------------------------------------------------------
    // v1.0 audio + animated background
    // ------------------------------------------------------------------------

    const bool musicAvailable =
        initBackgroundMusic();

    initializeAnimatedBackground();


    // ------------------------------------------------------------------------
    // Browser / popup state
    // ------------------------------------------------------------------------

    BrowserMode mode =
        BrowserMode::WUHB;

    BrowserState wuhbState = {
        0,
        0
    };

    BrowserState rpxState = {
        0,
        0
    };

    BrowserState elfState = {
        0,
        0
    };

    normalizeBrowserState(
        wuhbState,
        wuhbApps.size());

    normalizeBrowserState(
        rpxState,
        rpxApps.size());

    normalizeBrowserState(
        elfState,
        elfApps.size());

    std::string statusMessage;

    if (!wuhbUtilsAvailable) {
        statusMessage =
            "WUHB metadata/icons/validation unavailable.";
    }

    if (!musicAvailable) {

        if (!statusMessage.empty()) {
            statusMessage += "  ";
        }

        statusMessage +=
            "Music unavailable.";
    }

    VPADStatus vpadStatus = {};
    VPADReadError vpadError =
        VPAD_READ_SUCCESS;

    bool transitionRequested =
        false;

    bool confirmationActive =
        false;

    int confirmationButton =
        1;

    bool invalidWarningActive =
        false;

    bool noAppsConfirmationActive =
        wuhbApps.empty() &&
        rpxApps.empty() &&
        elfApps.empty();

    int noAppsConfirmationButton =
        1;

    bool creditsActive =
        false;

    // MINUS toggles a clean background-only view. While hidden, all controls
    // except MINUS are ignored so invisible UI cannot be changed accidentally.
    bool uiHidden =
        false;

    bool elfUnsupportedActive =
        false;

    bool pendingTouchOpen =
        false;

    bool screenDirty =
        true;

    bool wasDrawable =
        false;

    bool wasTouching =
        false;

    int secretProgress =
        0;

    OSTime secretLastInput =
        0;

    OSTime lastRenderTime =
        0;

    OSTime lastBackgroundUpdate =
        0;


    // ========================================================================
    // Main loop
    // ========================================================================

    while (WHBProcIsRunning()) {

        // Keep pumping ProcUI after requesting a launch/menu transition.
        if (transitionRequested) {
            OSSleepTicks(
                OSMillisecondsToTicks(
                    16));
            continue;
        }

        const bool drawable =
            ProcUIInForeground() &&
            gScreenBuffersReady;

        if (!drawable) {

            if (wasDrawable) {
                pauseBackgroundMusic();
            }

            wasDrawable =
                false;

            wasTouching =
                false;

            OSSleepTicks(
                OSMillisecondsToTicks(
                    16));

            continue;
        }

        if (!wasDrawable) {
            screenDirty = true;
            wasDrawable = true;
            resumeBackgroundMusic();
            lastRenderTime = 0;
            lastBackgroundUpdate = 0;
        }

        const OSTime now =
            OSGetTime();

        updateUiAnimations(
            now);

        const std::vector<AppEntry>* currentAppsPtr =
            &wuhbApps;

        BrowserState* currentStatePtr =
            &wuhbState;

        if (mode ==
            BrowserMode::RPX) {

            currentAppsPtr =
                &rpxApps;

            currentStatePtr =
                &rpxState;

        } else if (mode ==
                   BrowserMode::ELF) {

            currentAppsPtr =
                &elfApps;

            currentStatePtr =
                &elfState;
        }

        const std::vector<AppEntry>& currentApps =
            *currentAppsPtr;

        BrowserState& currentState =
            *currentStatePtr;

        normalizeBrowserState(
            currentState,
            currentApps.size());

        int selectedIndex =
            selectedIndexFor(
                currentApps.size(),
                currentState);


        // --------------------------------------------------------------------
        // A tapped card waits for the fast selection slide to settle, then
        // opens its confirmation / unsupported popup automatically.
        // --------------------------------------------------------------------

        if (pendingTouchOpen &&
            !gSelectionAnimation.active &&
            !gPageAnimation.active &&
            !confirmationActive &&
            !invalidWarningActive &&
            !noAppsConfirmationActive &&
            !creditsActive &&
            !elfUnsupportedActive) {

            pendingTouchOpen =
                false;

            selectedIndex =
                selectedIndexFor(
                    currentApps.size(),
                    currentState);

            if (selectedIndex >= 0) {

                const AppEntry& app =
                    currentApps[
                        static_cast<size_t>(
                            selectedIndex)];

                if (mode !=
                        BrowserMode::ELF &&
                    !app.valid) {

                    invalidWarningActive =
                        true;

                } else if (mode ==
                           BrowserMode::ELF) {

                    elfUnsupportedActive =
                        true;

                } else {

                    confirmationButton =
                        1;

                    confirmationActive =
                        true;
                }

                screenDirty =
                    true;
            }
        }


        // --------------------------------------------------------------------
        // Continuous v1.0 rendering using the Port13 motion model.
        // Background targets ~15 FPS, UI slides ~30 FPS, and movement uses
        // measured elapsed time so expensive frames do not create slow motion.
        // --------------------------------------------------------------------

        const bool backgroundCanAnimate =
            uiHidden ||
            (!creditsActive &&
             !confirmationActive &&
             !invalidWarningActive &&
             !noAppsConfirmationActive &&
             !elfUnsupportedActive);

        const bool backgroundDue =
            backgroundCanAnimate &&
            (lastBackgroundUpdate == 0 ||
             now - lastBackgroundUpdate >=
                 static_cast<OSTime>(
                     OSMillisecondsToTicks(
                         BACKGROUND_FRAME_MS)));

        const bool uiAnimationActive =
            gSelectionAnimation.active ||
            gPageAnimation.active;

        const bool uiAnimationFrameDue =
            uiAnimationActive &&
            (lastRenderTime == 0 ||
             now - lastRenderTime >=
                 static_cast<OSTime>(
                     OSMillisecondsToTicks(
                         UI_ANIMATION_FRAME_MS)));

        if (backgroundDue) {
            float elapsedSeconds =
                static_cast<float>(
                    BACKGROUND_FRAME_MS) /
                1000.0f;

            if (lastBackgroundUpdate != 0) {
                const OSTime ticksPerSecond =
                    OSMillisecondsToTicks(
                        1000);

                if (ticksPerSecond > 0) {
                    elapsedSeconds =
                        static_cast<float>(
                            now -
                            lastBackgroundUpdate) /
                        static_cast<float>(
                            ticksPerSecond);
                }
            }

            // Avoid a giant jump after a stall while preserving normal speed.
            elapsedSeconds =
                std::min(
                    elapsedSeconds,
                    0.125f);

            updateAnimatedBackground(
                elapsedSeconds *
                    BACKGROUND_ANIMATION_SPEED);

            lastBackgroundUpdate =
                now;
        }

        if (screenDirty ||
            backgroundDue ||
            uiAnimationFrameDue) {

            if (uiHidden) {

                drawBackgroundOnly();

            } else if (creditsActive) {

                drawCreditsScreen();

            } else if (
                noAppsConfirmationActive) {

                drawNoAppsConfirmationScreen(
                    noAppsConfirmationButton);

            } else if (
                invalidWarningActive &&
                selectedIndex >= 0) {

                drawInvalidAppWarningScreen(
                    currentApps[
                        static_cast<size_t>(
                            selectedIndex)]);

            } else if (
                elfUnsupportedActive &&
                selectedIndex >= 0) {

                drawELFUnsupportedScreen(
                    currentApps[
                        static_cast<size_t>(
                            selectedIndex)]);

            } else if (
                confirmationActive &&
                mode !=
                    BrowserMode::ELF &&
                selectedIndex >= 0) {

                drawLaunchConfirmationScreen(
                    currentApps[
                        static_cast<size_t>(
                            selectedIndex)],
                    confirmationButton);

            } else {

                drawBrowser(
                    mode,
                    currentApps,
                    currentState,
                    statusMessage);
            }

            presentScreens();
            screenDirty = false;
            lastRenderTime = now;
        }


        // --------------------------------------------------------------------
        // Input
        // --------------------------------------------------------------------

        const int32_t readCount =
            VPADRead(
                VPAD_CHAN_0,
                &vpadStatus,
                1,
                &vpadError);

        if (readCount > 0 &&
            vpadError ==
                VPAD_READ_SUCCESS) {

            const uint32_t pressed =
                vpadStatus.trigger;

            VPADTouchData calibratedTouch = {};

            VPADGetTPCalibratedPointEx(
                VPAD_CHAN_0,
                VPAD_TP_854X480,
                &calibratedTouch,
                &vpadStatus.tpFiltered1);

            const bool touching =
                calibratedTouch.touched != 0 &&
                calibratedTouch.validity ==
                    VPAD_VALID;

            const bool touchDown =
                touching &&
                !wasTouching;

            wasTouching =
                touching;

            const int touchX =
                static_cast<int>(
                    calibratedTouch.x);

            const int touchY =
                static_cast<int>(
                    calibratedTouch.y);

            bool launchConfirmed =
                false;


            // ================================================================
            // MINUS = hide / restore every UI element.
            //
            // While hidden, the animated background remains live and every
            // other input is ignored. Press MINUS again to restore exactly the
            // screen that was visible before entering background-only view.
            // ================================================================

            if (pressed &
                VPAD_BUTTON_MINUS) {

                uiHidden =
                    !uiHidden;

                gSelectionAnimation.active =
                    false;

                gPageAnimation.active =
                    false;

                pendingTouchOpen =
                    false;

                screenDirty =
                    true;

                OSSleepTicks(
                    OSMillisecondsToTicks(
                        16));

                continue;
            }

            if (uiHidden) {

                OSSleepTicks(
                    OSMillisecondsToTicks(
                        16));

                continue;
            }


            // ================================================================
            // Credits
            // ================================================================

            if (creditsActive) {

                if ((pressed &
                     (VPAD_BUTTON_A |
                      VPAD_BUTTON_B)) != 0 ||
                    touchDown) {

                    creditsActive =
                        false;

                    statusMessage.clear();
                    screenDirty = true;
                }

                OSSleepTicks(
                    OSMillisecondsToTicks(
                        16));

                continue;
            }


            // ================================================================
            // No-apps startup confirmation
            // ================================================================

            if (noAppsConfirmationActive) {

                if (pressed &
                    VPAD_BUTTON_PLUS) {

                    showStatusNow(
                        mode,
                        currentApps,
                        currentState,
                        "Scanning apps...");

                    wuhbUtilsAvailable =
                        rescanAppLists(
                            wuhbApps,
                            rpxApps,
                            elfApps);

                    normalizeBrowserState(
                        wuhbState,
                        wuhbApps.size());

                    normalizeBrowserState(
                        rpxState,
                        rpxApps.size());

                    normalizeBrowserState(
                        elfState,
                        elfApps.size());

                    noAppsConfirmationActive =
                        wuhbApps.empty() &&
                        rpxApps.empty() &&
                        elfApps.empty();

                    noAppsConfirmationButton =
                        1;

                    if (noAppsConfirmationActive) {

                        statusMessage.clear();

                    } else {

                        statusMessage =
                            "Apps rescanned.";

                        if (!wuhbUtilsAvailable) {
                            statusMessage +=
                                " WUHB metadata/icons/validation unavailable.";
                        }
                    }

                    screenDirty =
                        true;

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }

                int touchAction =
                    0;

                if (touchDown) {
                    touchAction =
                        confirmationButtonAt(
                            touchX,
                            touchY);
                }

                if (pressed &
                    (VPAD_BUTTON_LEFT |
                     VPAD_BUTTON_UP)) {

                    if (noAppsConfirmationButton != 1) {
                        noAppsConfirmationButton = 1;
                        screenDirty = true;
                    }

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }

                if (pressed &
                    (VPAD_BUTTON_RIGHT |
                     VPAD_BUTTON_DOWN)) {

                    if (noAppsConfirmationButton != 2) {
                        noAppsConfirmationButton = 2;
                        screenDirty = true;
                    }

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }

                if (touchAction != 0) {
                    noAppsConfirmationButton =
                        touchAction;
                }

                const bool menuRequested =
                    (pressed &
                     VPAD_BUTTON_B) != 0 ||
                    touchAction == 2 ||
                    ((pressed &
                      VPAD_BUTTON_A) != 0 &&
                     noAppsConfirmationButton == 2);

                if (menuRequested) {

                    pauseBackgroundMusic();

                    transitionRequested =
                        true;

                    SYSLaunchMenu();

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }

                const bool continueRequested =
                    touchAction == 1 ||
                    ((pressed &
                      VPAD_BUTTON_A) != 0 &&
                     noAppsConfirmationButton == 1);

                if (continueRequested) {

                    noAppsConfirmationActive =
                        false;

                    noAppsConfirmationButton =
                        1;

                    screenDirty = true;

                } else {

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }
            }


            // ================================================================
            // Invalid WUHB / RPX warning
            // ================================================================

            if (invalidWarningActive) {

                if ((pressed &
                     (VPAD_BUTTON_A |
                      VPAD_BUTTON_B)) != 0 ||
                    touchDown) {

                    invalidWarningActive =
                        false;

                    statusMessage.clear();
                    screenDirty = true;
                }

                OSSleepTicks(
                    OSMillisecondsToTicks(
                        16));

                continue;
            }


            // ================================================================
            // ELF unsupported popup
            // ================================================================

            if (elfUnsupportedActive) {

                if ((pressed &
                     (VPAD_BUTTON_A |
                      VPAD_BUTTON_B)) != 0 ||
                    touchDown) {

                    elfUnsupportedActive =
                        false;

                    statusMessage.clear();
                    screenDirty = true;
                }

                OSSleepTicks(
                    OSMillisecondsToTicks(
                        16));

                continue;
            }


            // ================================================================
            // WUHB / RPX confirmation:
            // D-Pad selects OK / Decline, A activates, B backs out,
            // and touchscreen buttons remain direct-select.
            // ================================================================

            if (confirmationActive) {

                int touchAction =
                    0;

                if (touchDown) {
                    touchAction =
                        confirmationButtonAt(
                            touchX,
                            touchY);
                }

                if (pressed &
                    (VPAD_BUTTON_LEFT |
                     VPAD_BUTTON_UP)) {

                    if (confirmationButton != 1) {
                        confirmationButton = 1;
                        screenDirty = true;
                    }

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }

                if (pressed &
                    (VPAD_BUTTON_RIGHT |
                     VPAD_BUTTON_DOWN)) {

                    if (confirmationButton != 2) {
                        confirmationButton = 2;
                        screenDirty = true;
                    }

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }

                if (touchAction != 0) {
                    confirmationButton =
                        touchAction;
                }

                const bool declineRequested =
                    (pressed &
                     VPAD_BUTTON_B) != 0 ||
                    touchAction == 2 ||
                    ((pressed &
                      VPAD_BUTTON_A) != 0 &&
                     confirmationButton == 2);

                if (declineRequested) {

                    confirmationActive =
                        false;

                    confirmationButton =
                        1;

                    statusMessage.clear();
                    screenDirty = true;

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }

                const bool launchRequested =
                    touchAction == 1 ||
                    ((pressed &
                      VPAD_BUTTON_A) != 0 &&
                     confirmationButton == 1);

                if (launchRequested &&
                    mode !=
                        BrowserMode::ELF &&
                    selectedIndex >= 0) {

                    confirmationActive =
                        false;

                    confirmationButton =
                        1;

                    launchConfirmed =
                        true;

                } else {

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }

            } else {

                // ============================================================
                // Secret classic-HBL Easter egg:
                // Up Up Up Down Down Down Left Right Left Right Y
                // ============================================================

                if (updateSecretCombo(
                        pressed,
                        secretProgress,
                        secretLastInput,
                        now)) {

                    gClassicMode =
                        !gClassicMode;

                    gSelectionAnimation.active =
                        false;

                    gPageAnimation.active =
                        false;

                    pendingTouchOpen =
                        false;

                    statusMessage =
                        gClassicMode
                            ? "Classic HBL mode activated!"
                            : "Classic HBL mode disabled.";

                    playSelectionSound();
                    screenDirty = true;

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }


                // ============================================================
                // X = Credits
                // ============================================================

                if (pressed &
                    VPAD_BUTTON_X) {

                    creditsActive =
                        true;

                    pendingTouchOpen =
                        false;

                    statusMessage.clear();
                    screenDirty = true;

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }


                // ============================================================
                // PLUS = rescan /wiiu/apps without restarting Aroma Launcher.
                // Y remains reserved for the classic-HBL easter egg.
                // ============================================================

                if (pressed &
                    VPAD_BUTTON_PLUS) {

                    showStatusNow(
                        mode,
                        currentApps,
                        currentState,
                        "Scanning apps...");

                    gSelectionAnimation.active =
                        false;

                    gPageAnimation.active =
                        false;

                    pendingTouchOpen =
                        false;

                    confirmationActive =
                        false;

                    confirmationButton =
                        1;

                    invalidWarningActive =
                        false;

                    elfUnsupportedActive =
                        false;

                    wuhbUtilsAvailable =
                        rescanAppLists(
                            wuhbApps,
                            rpxApps,
                            elfApps);

                    normalizeBrowserState(
                        wuhbState,
                        wuhbApps.size());

                    normalizeBrowserState(
                        rpxState,
                        rpxApps.size());

                    normalizeBrowserState(
                        elfState,
                        elfApps.size());

                    noAppsConfirmationActive =
                        wuhbApps.empty() &&
                        rpxApps.empty() &&
                        elfApps.empty();

                    noAppsConfirmationButton =
                        1;

                    if (noAppsConfirmationActive) {

                        statusMessage.clear();

                    } else {

                        statusMessage =
                            "Apps rescanned.";

                        if (!wuhbUtilsAvailable) {
                            statusMessage +=
                                " WUHB metadata/icons/validation unavailable.";
                        }
                    }

                    screenDirty =
                        true;

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }


                // ============================================================
                // ZL / ZR = cycle WUHB <-> RPX <-> ELF browser sections.
                // ZL goes backward; ZR goes forward.
                // ============================================================

                if (pressed &
                    (VPAD_BUTTON_ZL |
                     VPAD_BUTTON_ZR)) {

                    const bool previousSection =
                        (pressed &
                         VPAD_BUTTON_ZL) != 0;

                    if (previousSection) {

                        if (mode ==
                            BrowserMode::WUHB) {

                            mode =
                                BrowserMode::ELF;

                        } else if (mode ==
                                   BrowserMode::RPX) {

                            mode =
                                BrowserMode::WUHB;

                        } else {

                            mode =
                                BrowserMode::RPX;
                        }

                    } else {

                        if (mode ==
                            BrowserMode::WUHB) {

                            mode =
                                BrowserMode::RPX;

                        } else if (mode ==
                                   BrowserMode::RPX) {

                            mode =
                                BrowserMode::ELF;

                        } else {

                            mode =
                                BrowserMode::WUHB;
                        }
                    }

                    gSelectionAnimation.active =
                        false;

                    gPageAnimation.active =
                        false;

                    pendingTouchOpen =
                        false;

                    statusMessage.clear();
                    playSelectionSound();
                    screenDirty = true;

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }


                // ============================================================
                // GamePad touchscreen browser controls.
                // ============================================================

                if (touchDown &&
                    !gPageAnimation.active) {

                    const int pageDirection =
                        drcPageDirectionAt(
                            touchX,
                            touchY,
                            currentApps.size());

                    if (pageDirection != 0) {

                        if (changePageAnimated(
                                mode,
                                currentState,
                                currentApps.size(),
                                pageDirection,
                                now)) {

                            statusMessage.clear();
                            pendingTouchOpen = false;
                            screenDirty = true;
                        }

                        OSSleepTicks(
                            OSMillisecondsToTicks(
                                16));

                        continue;
                    }

                    const int touchedSlot =
                        drcCardSlotAt(
                            touchX,
                            touchY,
                            currentApps.size(),
                            currentState);

                    if (touchedSlot >= 0) {

                        if (setSelectionAnimated(
                                mode,
                                currentState,
                                currentApps.size(),
                                touchedSlot,
                                now)) {

                            pendingTouchOpen =
                                true;

                            statusMessage.clear();
                            screenDirty = true;

                        } else {

                            selectedIndex =
                                selectedIndexFor(
                                    currentApps.size(),
                                    currentState);

                            if (selectedIndex >= 0) {

                                const AppEntry& app =
                                    currentApps[
                                        static_cast<size_t>(
                                            selectedIndex)];

                                if (mode !=
                                        BrowserMode::ELF &&
                                    !app.valid) {

                                    invalidWarningActive =
                                        true;

                                } else if (mode ==
                                           BrowserMode::ELF) {

                                    elfUnsupportedActive =
                                        true;

                                } else {

                                    confirmationButton =
                                        1;

                                    confirmationActive =
                                        true;
                                }

                                statusMessage.clear();
                                screenDirty = true;
                            }
                        }

                        OSSleepTicks(
                            OSMillisecondsToTicks(
                                16));

                        continue;
                    }
                }


                // ============================================================
                // L / R = pages of four with horizontal slide.
                // ============================================================

                if (!gPageAnimation.active &&
                    (pressed &
                     VPAD_BUTTON_L)) {

                    if (changePageAnimated(
                            mode,
                            currentState,
                            currentApps.size(),
                            -1,
                            now)) {

                        statusMessage.clear();
                        pendingTouchOpen = false;
                        screenDirty = true;
                    }

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }

                if (!gPageAnimation.active &&
                    (pressed &
                     VPAD_BUTTON_R)) {

                    if (changePageAnimated(
                            mode,
                            currentState,
                            currentApps.size(),
                            1,
                            now)) {

                        statusMessage.clear();
                        pendingTouchOpen = false;
                        screenDirty = true;
                    }

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }


                // ============================================================
                // DOWN / UP = move selection, OG click + smooth focus slide.
                // ============================================================

                if (!gPageAnimation.active &&
                    (pressed &
                     VPAD_BUTTON_DOWN)) {

                    if (moveSelectionAnimated(
                            mode,
                            currentState,
                            currentApps.size(),
                            1,
                            now)) {

                        statusMessage.clear();
                        pendingTouchOpen = false;
                        screenDirty = true;
                    }

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }

                if (!gPageAnimation.active &&
                    (pressed &
                     VPAD_BUTTON_UP)) {

                    if (moveSelectionAnimated(
                            mode,
                            currentState,
                            currentApps.size(),
                            -1,
                            now)) {

                        statusMessage.clear();
                        pendingTouchOpen = false;
                        screenDirty = true;
                    }

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }


                // ============================================================
                // B = Wii U Menu
                // ============================================================

                if (pressed &
                    VPAD_BUTTON_B) {

                    showStatusNow(
                        mode,
                        currentApps,
                        currentState,
                        "Returning to Wii U Menu...");

                    pauseBackgroundMusic();

                    transitionRequested =
                        true;

                    SYSLaunchMenu();

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }


                // ============================================================
                // A = Open selected entry.
                // ============================================================

                if ((pressed &
                     VPAD_BUTTON_A) &&
                    selectedIndex >= 0) {

                    const AppEntry& app =
                        currentApps[
                            static_cast<size_t>(
                                selectedIndex)];

                    if (mode !=
                            BrowserMode::ELF &&
                        !app.valid) {

                        invalidWarningActive =
                            true;

                    } else if (mode ==
                               BrowserMode::ELF) {

                        // ELF execution belongs to legacy homebrew environments.
                        elfUnsupportedActive =
                            true;

                    } else {

                        // WUHB and RPX share the same launch confirmation path.
                        confirmationButton =
                            1;

                        confirmationActive =
                            true;
                    }

                    pendingTouchOpen =
                        false;

                    statusMessage.clear();
                    screenDirty = true;

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }
            }


            // ================================================================
            // CONFIRMED WUHB / RPX LAUNCH
            // ================================================================

            if (launchConfirmed &&
                mode !=
                    BrowserMode::ELF &&
                selectedIndex >= 0) {

                const AppEntry& app =
                    currentApps[
                        static_cast<size_t>(
                            selectedIndex)];

                if (!app.valid) {

                    invalidWarningActive =
                        true;

                    screenDirty = true;

                    OSSleepTicks(
                        OSMillisecondsToTicks(
                            16));

                    continue;
                }

                const std::string launchPath =
                    makeLaunchPath(
                        app.fullPath);

                statusMessage =
                    "Launching: " +
                    app.title;

                showStatusNow(
                    mode,
                    currentApps,
                    currentState,
                    statusMessage);

                OSSleepTicks(
                    OSMillisecondsToTicks(
                        100));

                // Stop/pause music before handing control to another app.
                pauseBackgroundMusic();

                const RPXLoaderStatus initResult =
                    RPXLoader_InitLibrary();

                if (initResult !=
                    RPX_LOADER_RESULT_SUCCESS) {

                    statusMessage =
                        "Launcher service unavailable: ";

                    statusMessage +=
                        RPXLoader_GetStatusStr(
                            initResult);

                    resumeBackgroundMusic();
                    screenDirty = true;

                } else {

                    const RPXLoaderStatus launchResult =
                        RPXLoader_LaunchHomebrew(
                            launchPath.c_str());

                    RPXLoader_DeInitLibrary();

                    if (launchResult ==
                        RPX_LOADER_RESULT_SUCCESS) {

                        // Sacred working transition behavior: do not break or
                        // shut ProcUI down here. Keep pumping until Aroma takes
                        // over the foreground/process transition.
                        transitionRequested =
                            true;

                    } else {

                        statusMessage =
                            "Could not launch " + app.title + ": ";

                        statusMessage +=
                            RPXLoader_GetStatusStr(
                                launchResult);

                        resumeBackgroundMusic();
                        screenDirty = true;
                    }
                }
            }
        }


        // Roughly 60 Hz input / ProcUI pump.
        OSSleepTicks(
            OSMillisecondsToTicks(
                16));
    }


    // ========================================================================
    // Cleanup
    // ========================================================================

    shutdownBackgroundMusic();

    if (gScreenBuffersReady) {

        OSScreenEnableEx(
            SCREEN_TV,
            false);

        OSScreenEnableEx(
            SCREEN_DRC,
            false);

        OSScreenShutdown();

        releaseForegroundBuffers(
            nullptr);
    }

    WHBProcShutdown();

    return 0;
}
